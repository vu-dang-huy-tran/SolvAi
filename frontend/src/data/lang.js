/**
 * Returns the translation function for the given language code.
 * Usage: const t = getT('en'); t('settings') → "Settings"
 */
export function getT(lang = DEFAULT_LANG) {
  const dict = translations[lang] || translations[DEFAULT_LANG];
  const fallback = translations[DEFAULT_LANG];
  return (key) => dict[key] !== undefined ? dict[key] : (fallback[key] !== undefined ? fallback[key] : key);
}

/**
 * Returns the full language name for a language code.
 */
export function getLanguageLabel(code) {
  const lang = LANGUAGES.find(l => l.code === code);
  return lang ? `${lang.flag} ${lang.label}` : code;
}

